@Composable
fun ConfirmActionDialog(
    title: String,
    message: String,
    confirmLabel: String,
    isDestructive: Boolean = true,
    onConfirm: () -> Unit,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = NavyElevated,
        title = {
            Text(text = title, style = MaterialTheme.typography.titleLarge)
        },
        text = {
            Text(
                text = message,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
        },
        confirmButton = {
            Button(
                onClick = onConfirm,
                colors = ButtonDefaults.buttonColors(
                    containerColor = if (isDestructive) CrimsonDanger else MaterialTheme.colorScheme.primary
                ),
                modifier = Modifier.testTag("confirm_dialog_button")
            ) {
                Text(confirmLabel)
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("إلغاء")
            }
        }
    )
}

@Composable
fun InvoiceReceiptDialog(
    invoice: InvoiceEntity,
    items: List<InvoiceItemEntity>,
    currency: String,
    showProfitDetails: Boolean,
    title: String = "فاتورة بيع #${invoice.id}",
    onDismiss: () -> Unit
) {
    val paymentType = PaymentType.fromCode(invoice.paymentType)
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = NavyElevated,
        title = {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(title, style = MaterialTheme.typography.titleLarge)
                StatusPill(
                    text = paymentType.labelAr,
                    color = if (paymentType == PaymentType.CASH) EmeraldProfit else MaterialTheme.colorScheme.secondary
                )
            }
        },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text(
                    text = "التاريخ: ${formatDateTime(invoice.createdAt)}",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                if (!invoice.customerNameSnapshot.isNullOrBlank()) {
                    Text(
                        text = "الزبون: ${invoice.customerNameSnapshot}",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.secondary
                    )
                }
                HorizontalDivider(color = NavyBorder)
                items.forEach { line ->
                    val unitLabel = SaleUnitType.fromCode(line.saleUnitType).labelAr
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(
                                text = "${line.productNameSnapshot} × ${line.quantity} $unitLabel",
                                style = MaterialTheme.typography.bodyMedium,
                                fontWeight = FontWeight.SemiBold
                            )
                            Text(
                                text = "سعر الوحدة: ${formatMoney(line.unitSalePrice, currency)} • خصم ${line.unitsDeducted} وحدة",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                        Text(
                            text = formatMoney(line.lineTotal, currency),
                            style = MaterialTheme.typography.bodyMedium,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.onSurface
                        )
                    }
                }
                HorizontalDivider(color = NavyBorder)
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text("الإجمالي", style = MaterialTheme.typography.titleMedium)
                    Text(
                        formatMoney(invoice.totalRevenue, currency),
                        style = MaterialTheme.typography.titleLarge,
                        color = MaterialTheme.colorScheme.primary
                    )
                }
                if (showProfitDetails) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text(
                            "التكلفة: ${formatMoney(invoice.totalCost, currency)}",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                        Text(
                            "الربح: ${formatMoney(invoice.totalProfit, currency)}",
                            style = MaterialTheme.typography.labelMedium,
                            color = EmeraldProfit,
                            fontWeight = FontWeight.Bold
                        )
                    }
                }
                if (invoice.notes.isNotBlank()) {
                    Text(
                        text = "ملاحظات: ${invoice.notes}",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
        },
        confirmButton = {
            Button(onClick = onDismiss, modifier = Modifier.testTag("close_receipt_button")) {
                Text("إغلاق")
            }
        }
    )
}
